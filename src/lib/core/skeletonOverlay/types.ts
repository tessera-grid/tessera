export interface SkeletonOptions {
  /**
   * number - фиксированное количество колонок для отрисовки скелетонов
   * auto - за основу берется реальное количество колонок, если они доступны заранее
   */
  columnsCount: number | 'auto'
  /**
   * number - фиксированное количество строк для отрисовки скелетонов
   * auto - за основу берется реальное количество данных, если они доступны заранее
   */
  rowsCount: number | 'auto'
  /**
   * grid - скелетоны соблюдают значения ширины реальной колонки, либо придерживаются максимально заданной ширины
   * flex - скелетоны занимают все доступное пространство между собой
   */
  layout: 'grid' | 'flex'
}
