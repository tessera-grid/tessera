import { MouseEvent, ReactNode } from 'react'

import { TableLabels } from '../localization'
import { CellComponentProps, HeaderComponentProps } from '../pluginContract'
import { SubscribeParamsType } from '../subscribeStore/subscribeStore'

/** Все слоты, в которых может жить действие (шапка + ячейка + строка действий). */
export type SlotName =
  | 'leftHeaderSlot'
  | 'rightHeaderSlot'
  | 'leftCellSlot'
  | 'rightCellSlot'
  | 'actionRowSlot'

/** Слоты заголовка (подмножество `SlotName` для действий шапки колонки). */
export type HeaderActionSlot = 'leftHeaderSlot' | 'rightHeaderSlot'

/**
 * Декларативное действие в заголовке колонки. Единственный источник правды для
 * кнопки заголовка: иконка/подпись/обработчик и признаки видимости, блокировки и
 * состояния-тумблера. Ядро само решает, как его показать — инлайн иконкой-кнопкой
 * или строкой раскрывающегося меню (кебаб), — поэтому плагин описывает действие
 * данными, а не готовым JSX.
 *
 * Дженерик по контексту `TCtx`: заголовок (`HeaderComponentProps`) или ячейка/
 * строка (`CellComponentProps`). Все признаки — функции от контекста: одно и то же
 * действие применяется к каждому инстансу слота и решает по нему (`getCanPin`,
 * `getIsSorted`, `row.original` и т.п.). Псевдонимы — `HeaderAction` / `RowAction`.
 */
export interface SlotAction<TCtx = any, TSlot extends SlotName = SlotName> {
  /** Уникальный id действия — ключ дедупликации при сборке. */
  id: string
  /** Слот, в котором отрисовывается действие. */
  slot: TSlot
  /**
   * Порядок относительно соседних действий: число — индекс вставки,
   * `'last'`/`undefined` — в конец (как у слотов, см. `registerSlotInto`).
   */
  order?: number | 'last'
  /**
   * Иконка действия (инлайн-кнопка и строка меню). Возвращать компонент, если
   * иконка тематизируема через `useIcons` — иконки живут в React-контексте, а не
   * на инстансе таблицы, поэтому чистая функция читает их не напрямую, а через
   * возвращаемый компонент.
   */
  icon: (ctx: TCtx) => ReactNode
  /**
   * Подпись действия: `aria-label`/тултип инлайн-кнопки и текст строки меню.
   * `labels` инъектируются ядром (локализация — React-контекст, недоступный
   * чистой функции напрямую).
   */
  label: (ctx: TCtx, labels: TableLabels) => string
  /**
   * Доступное имя ИНЛАЙН-кнопки (`aria-label`), если оно отличается от тултипа
   * `label` — напр. сортировка договаривает приоритет мультисорта, невидимый в
   * тултипе. По умолчанию берётся `label`. На строку меню не влияет.
   */
  ariaLabel?: (ctx: TCtx, labels: TableLabels) => string
  /**
   * Обработчик выбора действия (клик по инлайн-кнопке). `event` прокидывается для
   * действий, чьё поведение зависит от модификаторов (напр. Shift для накопления
   * мультисортировки). В разворот `menuItems` не участвует — у пунктов свои
   * обработчики.
   */
  onSelect: (
    ctx: TCtx,
    event?: MouseEvent<HTMLButtonElement>,
  ) => void
  /**
   * Применимо ли действие к этой колонке. `false` убирает его целиком (как
   * внутренний `return null` у компонента-кнопки) и не учитывает в пороге
   * схлопывания. По умолчанию применимо.
   */
  visible?: (ctx: TCtx) => boolean
  /** Заблокировано ли действие (кнопка/пункт неактивны, но видимы). */
  disabled?: (ctx: TCtx) => boolean
  /**
   * Состояние-тумблер (закреплено/отсортировано/сгруппировано): подсветка
   * инлайн-кнопки (`data-button-active`) и отметка в строке меню.
   */
  active?: (ctx: TCtx) => boolean
  /**
   * Ключи гранулярной подписки Pub-Sub (см. `useSubscribeStore`): примитивы, при
   * смене которых кнопка/пункт и решение о схлопывании перечитываются. Так
   * реактивность остаётся в декларации действия, а не в общем компоненте.
   */
  subscribe?: (ctx: TCtx) => SubscribeParamsType[]
  /**
   * Может ли действие уезжать в кебаб при схлопывании. `false` — остаётся инлайн
   * рядом с кебабом (аффорданс, которому не место в меню). По умолчанию `true`.
   */
  collapsible?: boolean
  /**
   * Класс инлайн-кнопки — контролируемый escape для плагин-специфичной подачи
   * (напр. акцент закреплённой колонки). На строку меню не влияет.
   */
  className?: (ctx: TCtx) => string | undefined
  /**
   * Довесок ИНЛАЙН-кнопки (бейдж и т.п.), рисуется рядом с иконкой в общем
   * anchor. Напр. бейдж приоритета мультисортировки. На подачу в меню и на порог
   * не влияет.
   */
  adornment?: (ctx: TCtx) => ReactNode
  /**
   * Разворот действия в НЕСКОЛЬКО пунктов меню (напр. сортировка: asc / desc /
   * сброс). Если задан — в кебаб-меню вместо одной строки рисуются эти пункты
   * (одной подгруппой). Инлайн-подача (одна кнопка) и вклад в порог (одно
   * действие) при этом не меняются.
   */
  menuItems?: (
    ctx: TCtx,
    labels: TableLabels,
  ) => HeaderMenuItem[]
  /**
   * Необязательный заголовок подгруппы действия в меню (`Menu.GroupLabel`).
   * Подгруппы визуально разделены независимо от наличия заголовка.
   */
  menuGroupLabel?: (labels: TableLabels) => string
}

/** Действие в слоте ЗАГОЛОВКА колонки (контекст — `HeaderComponentProps`). */
export type HeaderAction = SlotAction<HeaderComponentProps, HeaderActionSlot>

/** Действие в слоте действий СТРОКИ (контекст — `CellComponentProps`). */
export type RowAction = SlotAction<CellComponentProps, 'actionRowSlot'>

/**
 * Разрешённый пункт кебаб-меню (результат `SlotAction.menuItems`). В отличие от
 * дескриптора — поля уже вычислены с учётом `ctx`/`labels`: меню лишь отрисовывает.
 */
export interface HeaderMenuItem {
  /** Уникальный id пункта в пределах подгруппы. */
  id: string
  /** Текст пункта и `aria-label`. */
  label: string
  /** Иконка пункта. */
  icon?: ReactNode
  /** Обработчик выбора пункта. */
  onSelect: () => void
  /** Заблокирован ли пункт. */
  disabled?: boolean
  /** Отмечен ли пункт (галочка) — напр. текущее направление сортировки. */
  active?: boolean
}

/** Свёрнутый по всем слотам набор действий (аналог `RenderSlots`). */
export type SlotActions = Record<SlotName, SlotAction[]>

/**
 * Конфиг схлопывания ОДНОГО слота в кебаб-меню (разрешённый, per-slot). Наличие
 * записи для слота в `table.options.actionMenu` означает, что кебаб для него
 * включён.
 */
export interface SlotMenuConfig {
  /**
   * `auto` — схлопывать по порогу; `always` — схлопывать всегда, игнорируя
   * счётчик (форс из параметров плагина).
   */
  mode: 'auto' | 'always'
  /**
   * Порог схлопывания для `auto`: если суммарное число действий в слоте
   * (применимые дескрипторы + опаковые компоненты) достигает порога — все
   * схлопываемые дескрипторы уезжают в кебаб.
   */
  threshold: number
}

/**
 * Карта конфигов меню по слотам, свёрнутая ядром из деклараций активных плагинов-
 * меню. Ключ = слот, значение = его `SlotMenuConfig`; отсутствие ключа = кебаб для
 * слота выключен. Так разные плагины (заголовки/строки) не затирают друг друга.
 */
export type SlotActionMenu = Partial<Record<SlotName, SlotMenuConfig>>

/**
 * Декларация плагина-меню в записи реестра: на какие слоты распространить кебаб и
 * с какими `mode`/`threshold`. Ядро сворачивает декларации активных плагинов в
 * `SlotActionMenu` реактивно (как `slotActions`), поэтому отключение плагина
 * корректно убирает его слоты, а не оставляет устаревший конфиг.
 */
export interface ActionMenuDeclaration extends SlotMenuConfig {
  slots: SlotName[]
}
